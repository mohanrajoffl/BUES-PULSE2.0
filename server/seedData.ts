export function buildSchedulesFromBuses(buses: BusRecord[]): ScheduleItem[] {
  return buses.map((b) => ({
    schedule_id: `SCH-${b.bus_number}`,
    bus_id: b.bus_id,
    bus_number: b.bus_number,
    route_id: b.route_id,
    origin: b.origin,
    destination: b.destination,
    departure_time: b.departure_time,
    arrival_time: b.arrival_time,
    duration: b.duration,
    fare: b.fare,
    bus_type: b.bus_type,
    operating_days: b.operating_days,
    status: b.status,
    available_seats: b.available_seats,
  }));
}
